#!/usr/bin/env python3
"""Генератор проекта KiCad: Volt-Node - узел внутренней шины CAN FD, вольтметр.

Плата = ядро узла (lib/gen/core.py, стандарт docs/CORE.md) + измерительный
тракт. Здесь описан только тракт и то, где на этой плате стоит ядро.

Измерительный тракт повторяет volt_probe без изменений: щупы V+ / V- через
470 кОм (0805, 150 В) на дифференциальный усилитель LMV358 (половинка A),
коэффициент 18k/470k = 0.0383, выход смещён на опору 1.65 В (делитель 10k/10k
и буфер на половинке B). Диапазон +-43 В, пересчёт V = (OUT - 1.65) * 26.11.

Новое против volt_probe: АЦП теперь на плате. Аналог наружу не выходит, по
кабелю идёт только дифференциальный CAN. Опора 1.65 В заведена на второй канал
АЦП - её можно мерить, а не считать идеальной.

Выводы МК узла: PA0 (11) - измерение, PA1 (12) - контроль опоры.

Сейчас сделаны схема и размещение. Разводки нет: цепи видны связями.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "lib", "gen"))
import kicadenv
import pcbnew
from pcbhelp import Builder
import kigen
import core
import node
from core import C0402, R0402, R0805, SO8, SOT23, HDR2

OUT = sys.argv[1] if len(sys.argv) > 1 else "."
NAME = "Volt-Node"
X0, X1, Y0, Y1 = 100.0, 148.0, 100.0, 138.0
BW, BH = X1 - X0, Y1 - Y0
CXB, CYB = (X0 + X1) / 2, (Y0 + Y1) / 2

core.symbols(OUT)

b = Builder(layers=2)

# ------------------------------------------------------------ размещение
# По сторонам света: USB-C слева, шина сверху (J1) и снизу (J2), щупы справа
# (J4), микроконтроллер в центре. Каждая деталь тянется к своему разъёму или
# выводу МК. Разводки ещё нет, координаты будут уточняться.
#
# U1 развёрнут на 180: так его USB (33/34) смотрит влево на J3, АЦП (11/12)
# и кварц (8/9) - вправо, CAN (38/39) - вниз, на трансивер.
# Окна разъёмов наружу: J3 повёрнут на 270, J1 на 180 (окно вверх), J2 на 0
# (окно вниз) - передняя стенка каждого ровно по краю платы.
# Кнопки - зеркально относительно USB: на одном расстоянии от края и от его оси.
YM = CYB                      # ось USB и щупов - середина высоты
SWX, SWD = 105.2, 10.7        # кнопки: x и смещение от оси USB

core.place(b, {
    # центр: микроконтроллер и его развязка у выводов питания 4-6 (справа)
    "U1": (126.0, 118.0, 180),
    "C8": (132.4, 119.5, 90),
    "C10": (132.4, 122.0, 90),
    "C9": (128.8, 124.8, 0),
    "C11": (134.0, 126.3, 0),
    # кварц - справа от U1, у выводов 8/9; конденсаторы над и под ним
    "Y1": (137.3, 118.0, 90),
    "C5": (137.2, 113.9, 0),
    "C4": (137.2, 122.1, 0),
    # шина: J1 по центру сверху, J2 по центру снизу, трансивер между U1 и J2
    "J1": (129.0, Y0 + 6.3, 180),
    "J2": (123.0, Y1 - 6.3, 0),
    "U2": (123.5, 127.5, 0),
    "C6": (118.8, 126.6, 0),
    "C7": (118.8, 128.4, 0),
    "R8": (129.0, 127.5, 0),
    "JP1": (134.0, 128.8, 0),
    # USB-C по центру слева, CC-резисторы за ним
    "J3": (103.7, YM, 270),
    "R9": (111.0, YM - 1.5, 90),
    "R10": (111.0, YM + 1.5, 90),
    # питание: диод USB и LDO - между USB и U1, диод шины - у J2
    "D4": (115.5, 108.2, 180),
    "U3": (116.0, 113.5, 0),
    "C12": (112.5, 113.5, 90),
    "C13": (119.3, 112.8, 90),
    "C15": (119.3, 115.0, 90),
    "D3": (115.0, 133.5, 0),
    # кнопки: RESET над USB, BOOT под ним
    "SW1": (SWX, YM - SWD, 0),
    "SW2": (SWX, YM + SWD, 0),
    "R11": (118.5, 121.5, 90),
    "C14": (134.0, 124.3, 0),
    # светодиод
    "D5": (141.5, 124.5, 0),
    "R12": (141.5, 126.8, 0),
    # отладочная гребёнка вдоль верхнего края слева
    "J5": (102.3, 102.3, 90),
})

# --- аналоговый блок: правый верхний угол. J4 на правом краю по оси, R1/R2
# сразу за ним, U4 над ними, выход через R7/C1 - к выводам АЦП U1 (11/12).
b.place("J4", HDR2[0], HDR2[1], X1 - 2.3, YM - 1.27, 0, value="PROBE")
b.place("R1", R0805[0], R0805[1], 141.5, YM - 1.27, 0, value="470k")
b.place("R2", R0805[0], R0805[1], 141.5, YM + 1.27, 0, value="470k")
b.place("D1", SOT23[0], SOT23[1], 144.0, 108.3, 0, value="BAT54S")
b.place("D2", SOT23[0], SOT23[1], 144.0, 104.5, 0, value="BAT54S")
b.place("U4", SO8[0], SO8[1], 138.0, 108.0, 180, value="LMV358")
b.place("C3", C0402[0], C0402[1], 135.5, 112.2, 0, value="100nF")
b.place("R4", R0402[0], R0402[1], 139.5, 112.2, 0, value="18k")
b.place("R5", R0402[0], R0402[1], 133.3, 102.8, 0, value="10k")
b.place("R6", R0402[0], R0402[1], 135.6, 102.8, 0, value="10k")
b.place("C2", C0402[0], C0402[1], 137.9, 102.8, 0, value="100nF")
b.place("R3", R0402[0], R0402[1], 140.2, 102.8, 0, value="18k")
b.place("R7", R0402[0], R0402[1], 134.2, 114.3, 0, value="220R")
b.place("C1", C0402[0], C0402[1], 134.2, 116.7, 0, value="470pF")

# --- подписи: на плотной плате библиотечное место (над корпусом) налезает
# на соседей, уносим туда, где свободно
for _r, _x, _y, _a in (
        ("J5", 110.5, 104.9, 0), ("SW1", SWX, YM - SWD - 3.6, 0), ("SW2", SWX, YM + SWD + 3.6, 0),
        ("J3", 104.5, 112.4, 0), ("R9", 113.3, YM - 1.5, 0), ("R10", 113.5, YM + 1.5, 0),
        ("D4", 115.5, 105.0, 0), ("U3", 116.0, 116.2, 0), ("C13", 122.0, 110.6, 0), ("C15", 119.3, 117.2, 0),
        ("C6", 116.7, 126.6, 0), ("C7", 116.2, 128.4, 0), ("U2", 126.3, 127.5, 90), ("J2", 134.0, 133.5, 0),
        ("U1", 126.0, 118.0, 0), ("C9", 125.4, 124.6, 0), ("R8", 131.6, 127.5, 0),
        ("C8", 134.0, 119.5, 0), ("C10", 134.5, 122.0, 0), ("Y1", 137.3, 118.0, 0), ("C14", 136.4, 124.3, 0), ("C11", 136.4, 126.3, 0),
        ("JP1", 137.0, 128.8, 0), ("D5", 144.3, 124.5, 0), ("R12", 144.0, 126.8, 0),
        ("R1", 141.5, 115.6, 0), ("R2", 142.3, 122.4, 0), ("C4", 139.3, 122.1, 0), ("C5", 139.4, 113.9, 0),
        ("C3", 133.2, 111.9, 0), ("R4", 141.6, 112.2, 0), ("U4", 138.0, 108.0, 0),
        ("R7", 132.4, 114.4, 90), ("C1", 132.4, 116.9, 90), ("D2", 144.0, 101.6, 0), ("D1", 144.0, 111.0, 0)):
    b.label(_r, _x, _y, _a)

b.edge_rect(CXB, CYB, BW, BH, 1.5)

# ------------------------------------------------------------ схема
d = kigen.Design(NAME, "Volt-Node: вольтметр +-43 В, узел внутренней шины CAN FD")
d.prepare()

core.add(d, mcu={"11": "VOUT",     # PA0 - АЦП: измерение
                 "12": "VREF"})    # PA1 - АЦП: контроль опоры 1.65 В

# --- измерительный тракт: как в volt_probe, один в один
P = lambda ref, lib, val, fp, nets, at: d.add(kigen.Part(ref, lib, val, "%s:%s" % fp, nets, at=at))
P("U4", "Amplifier_Operational:LMV358", "LMV358", SO8,
  {"1": "AOUT", "2": "FB", "3": "INP", "4": "GND",
   "5": "VREFD", "6": "VREF", "7": "VREF", "8": "+3V3"}, (165, 45))
P("J4", "Connector_Generic:Conn_01x02", "PROBE", HDR2, {"1": "VIN+", "2": "VIN-"}, (55, 40))
P("R1", "Device:R", "470k", R0805, {"1": "VIN+", "2": "INP"}, (95, 25))
P("R2", "Device:R", "470k", R0805, {"1": "VIN-", "2": "FB"}, (95, 60))
P("R3", "Device:R", "18k", R0402, {"1": "INP", "2": "VREF"}, (130, 25))
P("R4", "Device:R", "18k", R0402, {"1": "FB", "2": "AOUT"}, (130, 60))
P("R5", "Device:R", "10k", R0402, {"1": "+3V3", "2": "VREFD"}, (235, 25))
P("R6", "Device:R", "10k", R0402, {"1": "VREFD", "2": "GND"}, (235, 60))
P("C2", "Device:C", "100nF", C0402, {"1": "VREFD", "2": "GND"}, (258, 60))
P("C3", "Device:C", "100nF", C0402, {"1": "+3V3", "2": "GND"}, (205, 25))
P("R7", "Device:R", "220R", R0402, {"1": "AOUT", "2": "VOUT"}, (285, 45))
P("C1", "Device:C", "470pF", C0402, {"1": "VOUT", "2": "GND"}, (308, 60))
# BAT54S: 1 - анод нижнего (GND), 2 - катод верхнего (3V3), 3 - средняя точка
P("D1", "Diode:BAT54S", "BAT54S", SOT23, {"1": "GND", "2": "+3V3", "3": "INP"}, (110, 90))
P("D2", "Diode:BAT54S", "BAT54S", SOT23, {"1": "GND", "2": "+3V3", "3": "FB"}, (150, 90))

# ------------------------------------------------------------ шелкография
# Надписи на обороте: лицевая сторона занята плотно.
b.text(NAME, CXB, 111.5, pcbnew.B_SilkS, 1.6, 0.25, mirror=True)
b.text("CAN FD 250k/1M   BUS 5V", CXB, 114.5, pcbnew.B_SilkS, 1.0, 0.18, mirror=True)

node.finish(b, d, OUT, NAME)
